const app = {
  currentLang: 'es',
  form: document.getElementById('booking-form'),
  status: document.querySelector('.form-status')
};

function setLanguage(lang) {
  app.currentLang = lang;

  const langMeta = document.querySelector('meta[property="og:locale"]');
  if (langMeta) {
    langMeta.setAttribute('content', translations[lang].lang_meta);
  }

  const description = document.querySelector('meta[name="description"]');
  const ogDescription = document.querySelector('meta[property="og:description"]');
  const twitterDescription = document.querySelector('meta[name="twitter:description"]');

  const localizedDescription =
    lang === 'es'
      ? 'El Rincón del Paraíso es una casita tranquila en Fortuna, Murcia, con piscina compartida, jacuzzi privado, ambiente rural y descanso total.'
      : lang === 'fr'
        ? 'El Rincón del Paraíso est une petite maison paisible à Fortuna, en Murcia, avec piscine partagée, jacuzzi privé et ambiance relaxante.'
        : 'El Rincón del Paraíso is a peaceful holiday house in Fortuna, Murcia, with a shared pool, private jacuzzi and a relaxing rural atmosphere.';

  if (description) description.setAttribute('content', localizedDescription);
  if (ogDescription) ogDescription.setAttribute('content', localizedDescription);
  if (twitterDescription) twitterDescription.setAttribute('content', localizedDescription);

  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll('.lang-btn').forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  const waLink = `https://wa.me/34611421863?text=${encodeURIComponent(translations[lang].whatsapp_message)}`;
  document.querySelectorAll('a[href*="wa.me"]').forEach((link) => {
    link.href = waLink;
  });

  const schema = {
    '@context': 'https://schema.org',
    '@type': 'LodgingBusiness',
    name: 'El Rincón del Paraíso',
    description: localizedDescription,
    address: {
      '@type': 'PostalAddress',
      addressLocality: 'Fortuna',
      addressRegion: 'Murcia',
      addressCountry: 'ES'
    },
    telephone: '+34 611 42 18 63',
    email: 'tu-email@ejemplo.com',
    sameAs: [
      'https://www.airbnb.fr/rooms/1255898519103350954?guests=1&adults=1&s=67&unique_share_id=5c5c9a0b-856a-4fbf-8e0b-a1b8c301ebaf'
    ],
    geo: {
      '@type': 'GeoCoordinates',
      latitude: '37.8900',
      longitude: '-1.1900'
    },
    amenityFeature: [
      { '@type': 'LocationFeatureSpecification', name: 'Piscina compartida' },
      { '@type': 'LocationFeatureSpecification', name: 'Jacuzzi privado' }
    ]
  };

  const schemaElement = document.getElementById('site-schema');
  if (schemaElement) {
    schemaElement.textContent = JSON.stringify(schema);
  }
}

function bindLanguageButtons() {
  document.querySelectorAll('.lang-btn').forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.dataset.lang));
  });
}

function bindMobileMenu() {
  const toggle = document.querySelector('.nav-toggle');
  const nav = document.querySelector('.main-nav');

  if (!toggle || !nav) return;

  toggle.addEventListener('click', () => {
    const isOpen = nav.classList.toggle('is-open');
    toggle.setAttribute('aria-expanded', String(isOpen));
  });

  nav.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => {
      nav.classList.remove('is-open');
      toggle.setAttribute('aria-expanded', 'false');
    });
  });
}

function bindGalleryLightbox() {
  const galleryItems = document.querySelectorAll('.gallery-item');
  const lightbox = document.querySelector('.lightbox');
  const lightboxImg = lightbox.querySelector('img');
  const closeButton = document.querySelector('.lightbox__close');

  if (!galleryItems.length || !lightbox || !lightboxImg || !closeButton) return;

  galleryItems.forEach((item) => {
    item.addEventListener('click', () => {
      lightboxImg.src = item.dataset.full;
      lightbox.classList.add('is-open');
      lightbox.setAttribute('aria-hidden', 'false');
    });
  });

  closeButton.addEventListener('click', () => {
    lightbox.classList.remove('is-open');
    lightbox.setAttribute('aria-hidden', 'true');
    lightboxImg.src = '';
  });

  lightbox.addEventListener('click', (event) => {
    if (event.target === lightbox) {
      lightbox.classList.remove('is-open');
      lightbox.setAttribute('aria-hidden', 'true');
      lightboxImg.src = '';
    }
  });
}

function handleBookingForm() {
  if (!app.form) return;

  app.form.addEventListener('submit', (event) => {
    event.preventDefault();

    const formData = new FormData(app.form);
    const name = formData.get('name')?.toString().trim() || 'Cliente';
    const email = formData.get('email')?.toString().trim() || 'sin-email';
    const checkin = formData.get('checkin')?.toString().trim() || '';
    const checkout = formData.get('checkout')?.toString().trim() || '';
    const guests = formData.get('guests')?.toString().trim() || '2';
    const message = formData.get('message')?.toString().trim() || '';

    const subject = encodeURIComponent(translations[app.currentLang].email_subject);
    const body = encodeURIComponent(
      `Nombre: ${name}\nE-mail: ${email}\nLlegada: ${checkin}\nSalida: ${checkout}\nNúmero de viajeros: ${guests}\n\nMensaje:\n${message}`
    );

    const mailLink = `mailto:tu-email@ejemplo.com?subject=${subject}&body=${body}`;
    window.location.href = mailLink;

    if (app.status) {
      app.status.textContent = translations[app.currentLang].form_status_success;
    }
  });
}

window.addEventListener('DOMContentLoaded', () => {
  bindLanguageButtons();
  bindMobileMenu();
  bindGalleryLightbox();
  handleBookingForm();
  setLanguage(app.currentLang);
});
